def TW_7g_from_WS(WS):
    """7g sustained turn constraint: TW = (q*Cd0)/WS + (k*n^2/q)*WS"""
    WS = np.maximum(WS, 1e-9)
    
    return (q_7g * C_D0_7g) / WS + (k_7g * (n_turn**2) / q_7g) * WS

#region (weight for 7g)
def inner_loop_weight_7g(W_guess, tol_W=1e-8, max_iter_W=100, relax_W=0.35):
    """
    Inner loop for diagram-consistent 7g:
    converges W -> W0_target (fixed).
    """
    W = float(max(W_guess, 1.0))
    hist = []
    for it in range(max_iter_W):
        W_new = (1 - relax_W) * W + relax_W * W0_target
        hist.append(W_new)
        rel = abs(W_new - W) / max(abs(W_new), 1e-9)
        W = W_new
        if rel < tol_W:
            return W, True, it+1, np.array(hist)
    return W, False, max_iter_W, np.array(hist)



