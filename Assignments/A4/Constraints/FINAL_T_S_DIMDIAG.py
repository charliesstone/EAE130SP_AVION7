# region outer cruise M2.0
def outer_loop_thrust_for_onepointsixmach_constraint(
    S_wing_grid,
    TOGW_guess_init,
    T_total_guess_init,
    num_engines,
    S_ht, S_vt, S_wet_fuselage,
    W_crew, W_payload,
    coef_1_cruise_constraint, coef_2_cruise_constraint,
    tol_T_rel=1e-6,
    max_iter_T=100,
    relax=1.0
):

    T_total_converged = []
    W0_converged = []
    iter_counts = []
    T_total_history_allS = []

    for S_wing in S_wing_grid:

        T_total = T_total_guess_init
        T_hist = []

        for k in range(max_iter_T):

            T_0 = T_total / num_engines

            W0, wconv, it_w= inner_loop_weight(
                TOGW_guess_init,
                S_wing, S_ht, S_vt, S_wet_fuselage,
                num_engines, W_crew, W_payload, T_0
            )

            WS = W0 / S_wing

            W_to = W0

            T_to = 0.6 * W_to
            T_cr = 0.5 * T_to

            
            W_cr = 0.9021 * W_to
            WS_new = (W_cr / W_to) * WS

            TW_req = (W_cr / W_to) / (T_cr / T_to) * (coef_1_cruise_constraint / WS_new + coef_2_cruise_constraint * WS_new)
            T_req = TW_req * W0

            T_hist.append(T_total)

            if abs(T_req - T_total) / max(abs(T_total), 1e-9) < tol_T_rel:
                T_total = T_req
                break

            T_total = (1 - relax) * T_total + relax * T_req

        T_total_converged.append(T_total)
        W0_converged.append(W0)
        iter_counts.append(k + 1)
        T_total_history_allS.append(np.array(T_hist))

    return (
        np.array(T_total_converged),
        np.array(W0_converged),
        np.array(iter_counts),
        T_total_history_allS,
    )



#region outer manuv 7g
def outer_loop_thrust_for_S_7g(S, T_guess=40000.0, W_guess=55000.0,
                              tol_T=1e-6, max_iter_T=200, relax_T=0.35,
                              tol_W=1e-8, max_iter_W=100):
    """
    Outer loop for diagram-consistent 7g:
      - inner loop: W -> W0_target
      - outer loop: T -> TW(W/S)*W
    """
    T = float(max(T_guess, 1.0))
    T_hist = []

    # inner loop (weight)
    W, wconv, itW, W_hist = inner_loop_weight_7g(W_guess, tol_W=tol_W, max_iter_W=max_iter_W)

    # outer loop (thrust)
    for itT in range(max_iter_T):
        WS = W / float(S)
        TW_req = float(TW_7g_from_WS(WS))
        T_req = TW_req * 6000

        T_hist.append(T)
        relT = abs(T_req - T) / max(abs(T), 1e-9)
        if relT < tol_T:
            return T_req, W, True, itT+1, np.array(T_hist), W_hist

        T = (1 - relax_T) * T + relax_T * T_req

    return T, W, False, max_iter_T, np.array(T_hist), W_hist
